package uk.gov.hmcts.reform.dev;

import java.time.LocalDateTime;

import org.springframework.boot.CommandLineRunner;
import org.springframework.stereotype.Component;

import uk.gov.hmcts.reform.dev.models.Task;
import uk.gov.hmcts.reform.dev.repositories.TaskRepository;

@Component
public class TaskDataSeeder implements CommandLineRunner {
    private final TaskRepository taskRepository;

    public TaskDataSeeder(TaskRepository taskRepository) {
        this.taskRepository = taskRepository;
    }

    @Override
    public void run(String... args) {
        int caseId = 1;

        // Check if tasks already exist for this case ID to prevent duplicates
        if (!taskRepository.findByCaseId(caseId).isEmpty()) {
            return;
        }

        // Varied components to mix and match into 100 unique, descriptive tasks
        String[] systems = {"CRM database", "legacy mainframes", "third-party identity APIs", "compliance logs", "internal archives", "billing gateways"};
        String[] documents = {"financial balance statements", "notarised identity proofs", "employment verification letters", "historical audit logs", "cross-border regulatory forms"};
        String[] teams = {"Legal Counsel", "Senior Risk Assessment team", "Data Privacy Officer", "Underwriting department", "Technical Support desk"};

        String[] statuses = {"Not started", "In progress", "On hold"};

        for (int i = 1; i <= 100; i++) {
            // Round-robin selection for varied testing data
            String sys = systems[i % systems.length];
            String doc = documents[i % documents.length];
            String team = teams[i % teams.length];
            String status = statuses[i % statuses.length];

            // Format short title
            String title = String.format("Task #%03d: Process and verify %s", i, doc);

            // Build a detailed, multi-sentence description text block
            String description = String.format(
                "Comprehensive review requirement for case file reference ID %d. " +
                "This automated ticket dictates that the assignee must extract all relevant %s from the %s. " +
                "Cross-reference all extracted biometric records, timestamps, and digital signatures against our internal compliance schema. " +
                "If any structural discrepancies, parsing formatting anomalies, or validation mismatches are discovered during processing, " +
                "escalate the transaction immediately to the %s for tier-2 resolution. " +
                "Ensure all steps are audited in accordance with standard operating procedures and privacy mandates.",
                caseId, doc, sys, team
            );

            // Stagger deadlines systematically over the coming weeks
            LocalDateTime dueDate = LocalDateTime.now().plusDays(2 + (i % 14)).plusHours(i % 24);

            // Persist to database
            taskRepository.create(new Task(
                0,          // ID auto-generated by DB
                caseId,     // Foreign key target
                title,      // Task Subject/Header
                description,// Multi-sentence technical narrative
                status,     // Operational state
                dueDate     // Temporal constraint
            ));
        }
    }
}